def tsv(path):
    csv.field_size_limit(10 ** 9)
    rows = list(csv.reader(open(path, encoding="utf-8"), delimiter="\t", quoting=csv.QUOTE_NONE))
    un = lambda s: s.replace("\\n", "\n").replace("\\r", "").replace("\\t", "\t").replace("\\\\", "\\")
    return [[un(c) for c in r] for r in rows[1:]]


