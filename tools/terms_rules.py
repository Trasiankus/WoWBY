def _lin(m):
    """linen (R126): «ільнян-» after a consonant or at the start, «льнян-» after a vowel (the previous word's last letter)."""
    s, i = m.string, m.start()
    j = i - 1
    while j >= 0 and s[j] == " ":
        j -= 1
    prev = s[j] if j >= 0 and j < i - 0 else ""
    at_start = j < 0 or not s[j].isalpha()
    cap = m.group(0)[0].isupper()
    if not at_start and j == i - 1:                      # glued to a letter (not a word start) — leave
        return m.group(0)
    if not at_start and prev.lower() in "аеёіоуыэюя":
        return ("Ль" if cap else "ль") + "нян"
    return ("Іль" if cap else "іль") + "нян"


