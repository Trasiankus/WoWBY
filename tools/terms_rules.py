def _zone_caps():
    """Place-name capitals (owner zone review 2026-10-03, review/zone_caps_final.json) as a standing rule, so text that
    arrives later (chunks translated before the review) gets them too. Only case-only changes; the name's later words
    keep their case ending and take the approved capital; the first word (the type: перавал, вёска…) is matched by stem
    and keeps the text's own case. Same logic as review/zone_caps_texts.py, which did the one-off pass."""
    import json
    fp = os.path.join(ROOT, "review", "zone_caps_final.json")
    if not os.path.exists(fp):
        return []
    L = "а-яёіўА-ЯЁІЎ'"

    def stem(w):
        return re.escape(w[:-2] if len(w) > 5 else w[:-1] if len(w) > 3 else w)
    rules = []
    for en, now, new in json.load(open(fp, encoding="utf-8")):
        a, b = now.split(" "), new.split(" ")
        if now.lower() != new.lower() or len(a) < 2 or len(a) != len(b):
            continue
        first = a[0]
        rx = "(?<![%s])(%s[%s]{0,4})" % (L, ("[%s%s]" % (first[0].upper(), first[0].lower()) + stem(first)[1:])
                                          if first[0].isalpha() else stem(first), L)
        for w in a[1:]:
            rx += r"(\s+)(%s[%s]{0,4})" % (stem(w), L)
        rx += "(?![%s])" % L
        caps = [x[:1].isupper() for x in b[1:]]

        def rep(m, caps=caps):
            g = m.groups(); out = g[0]
            for j, c in enumerate(caps):
                w = g[2 + 2 * j]
                out += g[1 + 2 * j] + (w[:1].upper() + w[1:] if c else w)
            return out
        rules.append((rx, rep))
    return rules


