# masculine adjective endings -> feminine, by the noun's case (plural adjectives have no gender)
_VEST_ADJ = {"": [("ыя", None), ("ы", "ая"), ("і", "ая")], "а": [("ага", "ай"), ("яга", "яй")],
             "у": [("аму", "ай"), ("яму", "яй")], "е": [("ым", "ай"), ("ім", "яй")], "ам": [("ым", "ай"), ("ім", "яй")]}
_VEST_ACC = [("ы", "ую"), ("і", "ую")]


def _vest(m):
    """vest = «камізэлька» (owner 2026-09-30, R131; not жылет/жылетка): noun by case + the adjectives before it made
    feminine («Скураны жылет» → «Скураная камізэлька»); after an imperative/infinitive the bare form is accusative."""
    adjs, cap, end = m.group(1), m.group(2) == "Ж", m.group(3)
    noun = _VEST_N[end]
    before = m.string[:m.start()].rstrip()
    acc = end == "" and re.search(r"(?:це|ць|ці)$", before) is not None
    if acc:
        noun = "камізэльку"
    words = adjs.split(" ")[:-1] if adjs else []
    table = _VEST_ACC if acc else _VEST_ADJ.get(end, [])
    out = []
    for w in words:
        for old, new in table:
            if w.endswith(old):
                if new is not None:
                    w = w[:-len(old)] + ("яя" if new == "ая" and w[:-len(old)].endswith("н") and w.lower().startswith("сін") else new)
                break
        out.append(w)
    if cap and not out:
        noun = noun[0].upper() + noun[1:]
    return "".join(x + " " for x in out) + noun


