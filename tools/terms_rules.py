def _place_rx():
    """Every reviewed place name of 2+ words (review/zone_caps_final.json, approved forms) as one inflection-tolerant
    regex: words matched by stem, any case. R189 (2026-10-07): spell names had «у бухту скарбаў», «логава чорнага
    крыла» — sentence_case lowercased the name part of a place."""
    global _PLACE_RX
    if _PLACE_RX is None:
        import json
        fp = os.path.join(ROOT, "review", "zone_caps_final.json")
        L = "а-яёіўА-ЯЁІЎ'"
        alts = {}
        rows = json.load(open(fp, encoding="utf-8")) if os.path.exists(fp) else []
        # cities the zone review did not list (R708: «Выклік смельчака з грамавога Уцёса»)
        rows += [[None, None, c] for c in EXTRA_PLACES]
        for row in rows:
            ws = row[2].split(" ")
            if len(ws) < 2 or not all(_WORD.fullmatch(w) for w in ws) or not any(w[0].isupper() for w in ws[1:]):
                continue
            st = [re.escape((w[:-2] if len(w) > 5 else w[:-1] if len(w) > 3 else w).lower()) for w in ws]
            alts[r"\s+".join("%s[%s]{0,4}" % (s, L) for s in st)] = [w[0].isupper() for w in ws]
        order = sorted(alts, key=len, reverse=True)
        _PLACE_RX = (re.compile("(?<![%s])(?:%s)(?![%s])" % (L, "|".join(order), L), re.I),
                     [(re.compile(a + "$", re.I), alts[a]) for a in order]) if alts else None
    return _PLACE_RX


def _place_caps(name):
    """Capitalise the name words (2nd on) of a known place inside a name; return (text, set of protected char starts)."""
    px, keep = _place_rx(), set()
    if not px:
        return name, keep

    def rep(m):
        caps = next((c for r, c in px[1] if r.match(m.group(0))), None)
        parts = re.split(r"(\s+)", m.group(0))
        if caps is None:
            return m.group(0)
        low = m.group(0).lower()
        city = low.startswith("бухт") and "скарб" in low         # Booty Bay is a city: «у Бухту Скарбаў» (owner)
        if city or not parts[0].lower().startswith(PLACE_TYPES):   # «Чорных Глыбінь», «Жудаснага Молата»: name
            keep.add(m.start())
            parts[0] = parts[0][:1].upper() + parts[0][1:]
        for j in range(2, len(parts), 2):
            if caps[j // 2]:
                keep.add(m.start() + sum(len(p) for p in parts[:j]))
                parts[j] = parts[j][:1].upper() + parts[j][1:]
        return "".join(parts)
    return px[0].sub(rep, name), keep


_SURNAME_RX = None


def _surname_keep(name):
    """R710 (owner 2026-10-21): two-word surnames («Рэнд Чорная Рука», «Горалук Расколатае Кавадла») keep their
    capitals in spell names; review/surname_final.json lists them, words matched by stem (any case form)."""
    global _SURNAME_RX
    if _SURNAME_RX is None:
        import json
        fp = os.path.join(ROOT, "review", "surname_final.json")
        L = "а-яёіўА-ЯЁІЎ'"
        alts = set()
        for f in (json.load(open(fp, encoding="utf-8")) if os.path.exists(fp) else []):
            for form in {f["m"], f["f"]}:
                ws = form.split()
                if len(ws) > 1:
                    alts.add(r"\s+".join("%s[%s]{0,4}" % (re.escape(w[:max(3, len(w) - 2)]), L) for w in ws))
        _SURNAME_RX = re.compile("(?<![%s])(?:%s)(?![%s])" % (L, "|".join(sorted(alts, key=len, reverse=True)), L)) if alts else False
    keep = set()
    if _SURNAME_RX:
        for m in _SURNAME_RX.finditer(name):
            if m.group(0)[0].isupper():
                pos = m.start()
                for part in re.split(r"(\s+)", m.group(0)):
                    if part and not part.isspace(): keep.add(pos)
                    pos += len(part)
    return keep


def sentence_case(name):
    pw = _proper_words()
    name, place_keep = _place_caps(name)
    place_keep |= _surname_keep(name)
    out, first = [], True
    toks = re.split(r"(\s+)", name)
    pos, starts = 0, []
    for tk in toks:
        starts.append(pos); pos += len(tk)
    for i, tok in enumerate(toks):
        if not tok or tok.isspace():
            out.append(tok); continue
        nxt = toks[i + 2].lower() if i + 2 < len(toks) else ""
        prv = toks[i - 2].lower() if i >= 2 else ""
        m = _WORD.match(tok.lstrip("«(\"'"))
        if first or not m or starts[i] in place_keep or nxt in ALWAYS_CAP or _clan(tok.lower(), prv, nxt):
            # «Срэбнага Світанку», «Дзікаму Молату», «бухты Скарбаў»: part of a name keeps its case
            out.append(tok)
        else:
            w = m.group(0)
            lw = w.lower()
            keep = ((not w[0].isupper()) or lw in pw["cap"] or lw not in pw["seen"] or w.isupper()
                    or lw in ALWAYS_CAP or tok.startswith("«"))
            out.append(tok if keep else tok.replace(w, w[0].lower() + w[1:], 1))
        # a sentence starts after ":" / dash / "(" / "«", and after a lead tag or step number («(DNT) Зняцце…»,
        # «[PH] Зняцце…», «— 1. Ініцыялізацыя»; 2026-10-17) when it begins the name or follows a sentence start
        first = (tok.rstrip().endswith((":", "—", "–", "(", "«"))
                 or (first and re.fullmatch(r"[\[(][A-Z]{2,4}[\])]|\d+\.", tok) is not None))
    return "".join(out)


