def _tabard(m):
    """tabard = «накідка» (owner 2026-10-01, R157; not табард): like _vest — noun by case, adjectives before it made
    feminine; object after an imperative/infinitive (…ць/…це/…ці, «Вазьмі», «насіў») or «на/у/праз/за»."""
    adjs, cap, end = m.group(1), m.group(2) == "Т", m.group(3)
    noun = _TABARD_N[end]
    before = m.string[:m.start()].rstrip()
    acc = end == "" and re.search(r"(?:це|ць|ці|Вазьмі|вазьмі|насіў|носіць|(?<![а-яёіўА-ЯЁІЎ])(?:[Нн]а|[УуЎў]|праз|за))$", before) is not None
    if acc:
        noun = "накідку"
    words = adjs.split(" ")[:-1] if adjs else []
    table = _VEST_ACC if acc else _VEST_ADJ.get("е" if end == "зе" else end, [])
    out = []
    for w in words:
        for old, new in table:
            if w.endswith(old):
                if new is not None:
                    w = w[:-len(old)] + new
                break
        out.append(w)
    if cap and not out:
        noun = noun[0].upper() + noun[1:]
    return "".join(x + " " for x in out) + noun


def _arcane(m):
    """Arcane school = «аркана» (owner 2026-09-30, R144; not тайная / таемная / таямнічая магія): case by the form."""
    cap, noun = m.group(1)[0].isupper(), m.group(2)
    before = m.string[:m.start()].rstrip().lower()
    if noun == "я": w = "аркана"
    elif noun == "ю": w = "аркану"
    elif noun == "яй": w = "арканай"
    else: w = "аркане" if re.search(r"(?:супраціўленн[еяю]|супраціў[уы]?)$", before) else "арканы"
    return ("А" if cap else "а") + w[1:]


def _akanne_apos(w):
    """Apostrophe name: every о/О before the last о/ё → а/А (R292)."""
    last = max(w.rfind(c) for c in "оОёЁ")
    return "".join({"о": "а", "О": "А"}.get(c, c) if i < last else c for i, c in enumerate(w))


