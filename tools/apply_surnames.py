"""Apply the owner's surname decisions (data/surname_decisions.tsv) to every family member's name.

    python tools/apply_surnames.py      (then python tools/build_addon.py)

Writes the generated block of data/names_fix.tsv (full EN name -> full BE name; the hand rows above the marker
stay), appends the family forms to data/glossary_forever.tsv (for the translator), and reports which shipped
quest texts still use an old form. Female members get the feminine form where the surname is an adjective or
an agent (PAIRS / "m / f" in the decision); noun surnames (Камнерук, Лютасць Буры) never change."""
import csv, json, os, re, sys, collections

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from surname_families import load_names  # noqa: E402

ROOT = os.path.normpath(os.path.join(os.path.dirname(os.path.abspath(__file__)), ".."))
TB = r"C:\Projects\WoW\turtle-bel"
MARK = "# --- generated by tools/apply_surnames.py (data/surname_decisions.tsv) — do not edit below ---"
# (masculine, feminine) where the decision gave only one of them
PAIRS = {"Dawnstrider": ("Світанкавы Вандроўнік", "Світанкавая Вандроўніца"),
         "Deepforge": ("Глыбакаваны", "Глыбакаваная"),
         "Maneweaver": ("Ткач Грывы", "Ткачыха Грывы"),
         "Swiftstrider": ("Шпаркі Вандроўнік", "Шпаркая Вандроўніца"),
         "Raincaller": ("Заклінальнік Дажджу", "Заклінальніца Дажджу"),
         "Nightrunner": ("Начны Бягун", "Начная Бягуння"),
         "Moonweaver": ("Месяцовы Ткач", "Месяцовая Ткачыха"),
         # a role, not a family (the Russian writes it lowercase): lowercase inside the name
         "Earthcaller": ("заклінальнік зямлі", "заклінальніца зямлі")}
FEM_END = re.compile(r"(ая|яя|іца|ыха|ння|чка)$")


def main():
    sys.stdout.reconfigure(encoding="utf-8")
    csv.field_size_limit(10 ** 9)
    dec = {r[0]: r[1] for r in list(csv.reader(open(os.path.join(ROOT, "data", "surname_decisions.tsv"), encoding="utf-8"),
                                               delimiter="\t"))[1:] if len(r) >= 2 and r[1]}
    sex = {}
    for r in csv.reader(open(os.path.join(TB, "data", "npc_sex.tsv"), encoding="utf-8"), delimiter="\t"):
        if len(r) >= 2: sex[r[0]] = r[1]
    names = load_names()
    first_count = collections.Counter(en.split()[0] for en in names if len(en.split()) == 2)
    out, old_forms, n_fam, pairs_old = [], collections.defaultdict(set), collections.Counter(), []
    for en, be in sorted(names.items()):
        w = en.split()
        if len(w) != 2 or w[1] not in dec: continue
        fam = w[1]
        if first_count[w[0]] >= 2: continue                 # "Gelkis Earthcaller": a clan unit, not a person
        b = be.split(" ", 1)
        if len(b) < 2: continue
        given, cur = b
        if not cur[:1].isupper() and fam not in PAIRS: continue   # word order differs: not "Given Surname"
        female = sex.get(en) == "female" or bool(FEM_END.search(cur))
        m, f = PAIRS.get(fam) or ((dec[fam].split(" / ") + [None])[:2])
        form = (f or m) if female else m
        if fam in PAIRS and female is False and dec[fam] == PAIRS[fam][1]:
            form = PAIRS[fam][0]
        if cur != form:
            old_forms[fam].add(cur)
            pairs_old.append((fam, given, cur, form))
            out.append((en, given + " " + form))
            n_fam[fam] += 1
    p = os.path.join(ROOT, "data", "names_fix.tsv")
    text = open(p, encoding="utf-8").read()
    head = text.split(MARK)[0].rstrip("\n")
    with open(p, "w", encoding="utf-8", newline="\n") as fh:
        fh.write(head + "\n" + MARK + "\n")
        for en, be in out: fh.write("%s\t%s\tsurname decision\n" % (en, be))
    # translator glossary: the family forms
    gp = os.path.join(ROOT, "data", "glossary_forever.tsv")
    gl = open(gp, encoding="utf-8").read()
    gmark = "# --- surnames (tools/apply_surnames.py) ---"
    gl = gl.split(gmark)[0].rstrip("\n") + "\n" + gmark + "\n"
    for fam, form in sorted(dec.items()):
        pair = PAIRS.get(fam)
        shown = "%s / %s" % pair if pair else form
        gl += "%s\t%s\tsurname (owner 2026-09-25): one form for every member%s\n" % (
            fam, pair[0] if pair else form.split(" / ")[0], "; " + shown if " / " in shown else "")
    open(gp, "w", encoding="utf-8", newline="\n").write(gl)
    with open(os.path.join(ROOT, "out", "surname_renames.tsv"), "w", encoding="utf-8", newline="\n") as fh:
        fh.write("family\tgiven\told\tnew\n")
        for fam, given, cur, form in pairs_old: fh.write("%s\t%s\t%s\t%s\n" % (fam, given, cur, form))
    print("renamed %d NPCs in %d families -> data/names_fix.tsv, out/surname_renames.tsv" % (len(out), len(n_fam)))
    # quest texts that still mention an old form (nominative or a declined head word)
    shipped = ""
    for fn in ("quests.lua", "forever.lua", "gossip.lua"):
        fp = os.path.join(ROOT, "addon", "WoWBY", "data", fn)
        if os.path.exists(fp): shipped += open(fp, encoding="utf-8").read()
    hits = collections.Counter()
    for fam, given, cur, form in pairs_old:                   # given name (any ending) + the old surname's start
        g = re.escape(given[:max(3, len(given) - 2)])
        o = re.escape(cur.split()[0][:max(3, len(cur.split()[0]) - 2)])
        hits[(fam, given + " " + cur)] = len(re.findall(g + r"[а-яёіўА-ЯЁІЎ']*\s+" + o, shipped))
    shown = [(k, v) for k, v in hits.items() if v]
    print("old full names still in shipped quest/gossip text: %d names, %d mentions" % (len(shown), sum(v for _, v in shown)))
    for (fam, f), v in sorted(shown, key=lambda kv: -kv[1])[:30]: print("   %-14s %-36s %d" % (fam, f, v))


if __name__ == "__main__":
    main()
