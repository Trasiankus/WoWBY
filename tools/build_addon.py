def lua_pattern(en):
    """EN template -> anchored Lua pattern with one (.-) capture per token, + the token list."""
    out, toks, pos = ["^"], [], 0
    for m in TOKEN.finditer(en):
        out.append(re.sub(r"([\^\$\(\)%\.\[\]\*\+\-\?])", r"%\1", en[pos:m.start()]))
        out.append("(.-)"); toks.append(m.group(0)); pos = m.end()
    out.append(re.sub(r"([\^\$\(\)%\.\[\]\*\+\-\?])", r"%\1", en[pos:]))
    # a template ending in " $@spelldesc1243969" (Forever food: the extra-XP sentence, empty without that buff): the
    # tooltip then ends at "15 min." with no space after it, so the space before a LAST capture is optional (R279)
    if len(out) >= 3 and out[-1] == "" and out[-2] == "(.-)" and out[-3].endswith(" "):
        out[-3] = out[-3].rstrip(" ") + "%s*"
    return "".join(out) + "$", toks


def _cond_parse(s):
    """'a $?s1[X][Y] b' -> ['a ', [[branch X seq], [branch Y seq]], ' b'] (strings and conditionals alternate, the
    list starts and ends with a string). WoW chains: $?c1[A]?c2[B][C]. None if the brackets don't balance."""
    out, buf, i = [], [], 0

    def bracket(i):                          # s[i] == "[" -> (content, index after the matching "]")
        depth, j = 0, i
        while j < len(s):
            if s[j] == "[": depth += 1
            elif s[j] == "]":
                depth -= 1
                if depth == 0: return s[i + 1:j], j + 1
            j += 1
        return None, i
    while i < len(s):
        if s.startswith("$?", i) and s.find("[", i) > 0:
            i = s.find("[", i)
            branches = []
            while True:
                body, i = bracket(i)
                if body is None: return None
                sub = _cond_parse(body)
                if sub is None: return None
                branches.append(sub)
                if s.startswith("?", i) and s.find("[", i) > 0 and "]" not in s[i:s.find("[", i)] \
                        and " " not in s[i:s.find("[", i)].strip():
                    i = s.find("[", i); continue
                if s.startswith("[", i):
                    body, i = bracket(i)
                    sub = None if body is None else _cond_parse(body)
                    if sub is None: return None
                    branches.append(sub)
                break
            out.append("".join(buf)); buf = []
            out.append(branches)
        else:
            buf.append(s[i]); i += 1
    out.append("".join(buf))
    return out


_ONE_VALUE = re.compile(r"\s*(?:[\d.,%]*|\$\{[^}]*\}|\$\d*[a-zA-Z]+\d*)\s*")


def _cond_joint(a, b, ctr, limit=64):
    """Parsed EN + BE sequences -> [(en_variant, be_variant)], the same branch picked on both sides. A conditional whose
    EN branches are each one number / token ("$?$PL<10[28]?$PL<20[71][90]") becomes one capture token instead."""
    if len(a) != len(b): return None
    res = [("", "")]
    for x, y in zip(a, b):
        if isinstance(x, str) != isinstance(y, str): return None
        if isinstance(x, str):
            res = [(e + x, t + y) for e, t in res]; continue
        if len(x) != len(y): return None
        if all(len(br) == 1 and _ONE_VALUE.fullmatch(br[0]) for br in x):
            ctr[0] += 1
            tok = "$zzcond%d" % ctr[0]
            res = [(e + tok, t + tok) for e, t in res]; continue
        opts = []
        for bx, by in zip(x, y):
            sub = _cond_joint(bx, by, ctr, limit)
            if sub is None: return None
            opts += sub
        res = [(e + oe, t + ot) for e, t in res for oe, ot in opts]
        if len(res) > limit: return None
    return res


def desc_variants(en, be):
    """[(en, be)] — the template itself, or one pair per branch combination of its `$?` conditionals (R562)."""
    if "$?" not in en: return [(en, be)]
    pa, pb = _cond_parse(en), _cond_parse(be)
    if pa is None or pb is None: return [(en, be)]
    out = _cond_joint(pa, pb, [0])
    if not out: return [(en, be)]
    seen, uniq = set(), []
    for e, t in out:
        if e not in seen: seen.add(e); uniq.append((e, t))
    return uniq


def desc_sections(en, be):
    """R809: a header + a chain of independent optional paragraphs, each `$?a123[text\\n\\n][]`, too many combinations to
    list (Camp Benefits: 9 camp objects = 512): 'sections={head pattern, head BE, {pattern, parts}, …}', matched paragraph by
    paragraph at runtime (spells.lua render_sections). None for any other shape."""
    pa, pb = _cond_parse(en), _cond_parse(be)
    if not pa or not pb or len(pa) != len(pb) or len(pa) < 3: return None
    if any(not isinstance(x, str) or x.strip() for x in pa[2::2] + pb[2::2]): return None
    if not (pa[0].endswith("\n\n") and pb[0].endswith("\n\n")): return None
    head, toks = lua_pattern(pa[0].rstrip())
    if toks: return None
    conds = list(zip(pa[1::2], pb[1::2]))
    items = []
    for n, (x, y) in enumerate(conds):
        if isinstance(x, str) or isinstance(y, str) or len(x) != len(y) or len(x) not in (1, 2): return None
        if len(x) == 2 and (x[1] != [""] or y[1] != [""]): return None
        for e, t in _cond_joint(x[0], y[0], [0]) or []:
            if n < len(conds) - 1 and not (e.endswith("\n\n") and t.endswith("\n\n")): return None
            pat, toks = lua_pattern(e.rstrip())
            parts = be_parts(t.rstrip(), toks)
            if parts is None or pat.endswith("(.-)$") or "$" in pat.replace("%$", "")[:-1]: return None
            items.append("{%s,{%s}}" % (lua_str(pat[1:-1]), ",".join(parts)))
    if not items: return None
    return "sections={%s,%s,%s}" % (lua_str(head[1:-1]), lua_str(pb[0]), ",".join(items))


def desc_sd(en, be):
    """SD entry body "pat,{parts}[,pat2,{parts2}…]" or None."""
    if "$?" in en and desc_variants(en, be) == [(en, be)]:
        s = desc_sections(en, be)
        if s: return s
    items = []
    for e, t in desc_variants(en, be):
        pat, toks = lua_pattern(e)
        parts = be_parts(t, toks)
        if parts is None or "$" in pat.replace("%$", "")[:-1]: continue
        items.append("%s,{%s}" % (lua_str(pat), ",".join(parts)))
    return ",".join(items) if items else None


def be_parts(be, toks):
    """BE template -> Lua list: literal strings, capture indexes, {male,female} for $g. None if unusable."""
    parts, pos = [], 0
    for m in TOKEN.finditer(be):
        if be[pos:m.start()]: parts.append(lua_str(be[pos:m.start()]))
        t = m.group(0); pos = m.end()
        if t[1] in "lL":
            # $lone:few:many; → WoW's own |4one:few:many; escape, resolved at runtime by the number before it
            # (core render_desc → W.plural_forms). It used to be dropped: «Выклікае 1 на дапамогу…» lost its noun (R553)
            body = t[2:-1] if t.endswith(";") else t[2:]
            parts.append(lua_str("|4" + body + ";")); continue
        if t[1] in "gG" and ":" in t:
            mf = t[2:-1].split(":", 1); parts.append("{%s,%s}" % (lua_str(mf[0]), lua_str(mf[1]))); continue
        if t not in toks:
            return None
        parts.append(str(toks.index(t) + 1))
    if be[pos:]: parts.append(lua_str(be[pos:]))
    return parts


