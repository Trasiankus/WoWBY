def turtle_data_lua(fname):
    """turtle-bel's generated addon data file (one global table: quests by id with t/d/o/p/c, or EN -> BE maps)
    -> the same Lua with every Belarusian value taken from data/be/tb_<name>.json. Quests / names / places Forever
    cannot show (TBC quests, Turtle-only and TBC NPCs and places; tools/forever_scope.py) are left out and parked (R718)."""
    import lupa
    text = open(os.path.join(SRC, "data", fname), encoding="utf-8").read()
    head, _, _ = text.partition("= {")
    gname = head.strip().splitlines()[-1].strip()
    lua = lupa.LuaRuntime(unpack_returned_tuples=True)
    lua.execute(text)
    tbl = lua.globals()[gname]
    dom = "tb_" + fname[:-4]
    out = [head.rstrip() + " = {"]
    rows = []
    for k, v in tbl.items():
        k = str(k)
        if not in_scope(dom, k):
            for key in ([k] if isinstance(v, str) else ["%s.%s" % (k, f) for f in dict(v.items())]):
                corpus(dom).park(key)
            continue
        if isinstance(v, str):
            rows.append((k, "[%s]=%s," % (lua_str(k), lua_str(cget(dom, k, v)))))
        else:
            fields = dict(v.items())
            order = [f for f in ("t", "d", "o", "p", "c") if f in fields] + sorted(f for f in fields if f not in "tdopc")
            body = ",".join("%s=%s" % (f, lua_str(cget(dom, "%s.%s" % (k, f), fields[f]))) for f in order)
            rows.append((k, "[%s]={%s}," % (lua_str(k), body)))
    rows.sort(key=lambda kv: (0, int(kv[0])) if kv[0].isdigit() else (1, kv[0]))
    out += [r for _, r in rows]
    out.append("}")
    return "\n".join(out) + "\n"


