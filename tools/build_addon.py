def esc(s):
    return s.replace("\\", "\\\\").replace('"', '\\"').replace("\r", "").replace("\n", "$B")


LUA_MAGIC = re.compile(r"([\^$()%.\[\]*+\-?])")
OA_CUT = re.compile(r"\$[Gg][^;]*;|\$[A-Za-z0-9]+|<[^>]*>|\n")      # context stops at tokens, narration, breaks


def oa_patterns(en_q, be_q):
    """$1oa / $2oa (objective amount) in the Belarusian text: the number is only in the live English text, so
    ship a Lua pattern per amount — the literal English around the token (up to 24 chars, not crossing another
    token or a line break) with the number captured: "bring her (%d+) Gnarlpine Fangs"."""
    need = {int(m) for v in be_q.values() for m in re.findall(r"\$(\d+)oa", v or "")}
    out = {}
    for f in ("o", "d", "p", "c"):
        t = (en_q.get(f) or "").replace("\r\n", "\n")
        for m in re.finditer(r"\$(\d+)oa", t):
            k = int(m.group(1))
            if k not in need or k in out: continue
            before = re.split(OA_CUT, t[:m.start()])[-1][-24:]
            after = re.split(OA_CUT, t[m.end():])[0][:24]
            if before.strip() or after.strip():
                out[k] = LUA_MAGIC.sub(r"%\1", before) + "(%d+)" + LUA_MAGIC.sub(r"%\1", after)
    return out


