FMT_TOKEN = re.compile(r"%(?:(\d+)\$)?[-+ #0]*\d*(?:\.\d+)?[sdfgixXc]|%%")


def fmt_pattern(en):
    """Forever EN format string -> (anchored Lua pattern, #tokens, {argument number: capture index}). A %s right after
    |c captures the 8-hex colour; %d captures a number; other tokens capture lazily. Captures come in the order the
    tokens stand in the EN text, which is not the argument order when EN uses %N$ ("%2$d/%3$d %1$s slain", R322)."""
    out, n, pos, argmap = ["^"], 0, 0, {}
    for m in FMT_TOKEN.finditer(en):
        lit = en[pos:m.start()]
        out.append(_esc_lit(lit))
        pos = m.end()
        if m.group(0) == "%%":
            out.append("%%"); continue
        n += 1
        argmap[int(m.group(1)) if m.group(1) else n] = n
        if lit.endswith("|c") and m.group(0).endswith("s"):
            out.append("(%x%x%x%x%x%x%x%x)")
        elif m.group(0)[-1] in "di":
            out.append("(%-?[%d,%.]+)")
        elif m.group(0)[-1] == "c":                       # the sign in "+4 Spirit" (ITEM_MOD_*: "%c%s Spirit", R109)
            out.append("([%+%-])")
        else:
            out.append("(.-)")
    out.append(_esc_lit(en[pos:]))
    return "".join(out) + "$", n, argmap


def _esc_lit(lit):
    """Literal EN text -> Lua pattern. "|4Slot:Slots;" (plural escape) may reach the tooltip raw or already
    resolved ("Slots"): a lazy letters-or-escape run matches both without adding a capture."""
    return "".join(_plural_pat(p) if p.startswith("|4") else re.sub(r"([\^\$\(\)%\.\[\]\*\+\-\?])", r"%\1", p)
                   for p in re.split(r"(\|4[^;]*;)", lit))


def _plural_pat(p):
    """"|4hour:hours;" -> "hour[s]-": only the escape's own word forms. A lazy any-letters run let "3 min" match the
    HOURS format → «3 гадзін» (R116). Forms without a common stem keep the lazy run."""
    forms = p[2:-1].split(":")
    stem = os.path.commonprefix(forms)
    rest = "".join(sorted(set("".join(f[len(stem):] for f in forms))))
    if len(stem) < 2:
        return "[%a|4:;' ]-"
    return re.sub(r"([\^\$\(\)%\.\[\]\*\+\-\?])", r"%\1", stem) + ("[" + rest + "]-" if rest else "")


def fmt_parts(be, n, argmap=None):
    """BE format string -> Lua parts (literals + 1-based capture indexes). %N$ in BE is an ARGUMENT number → the
    capture holding it (argmap from fmt_pattern). None if it references a token the EN side doesn't have."""
    parts, pos, seq = [], 0, 0
    for m in FMT_TOKEN.finditer(be):
        if be[pos:m.start()]: parts.append(lua_str(be[pos:m.start()]))
        pos = m.end()
        if m.group(0) == "%%":
            parts.append(lua_str("%")); continue
        seq += 1
        arg = int(m.group(1)) if m.group(1) else seq
        idx = (argmap or {}).get(arg, arg if argmap is None else None)
        if idx is None or not 1 <= idx <= n:
            return None
        parts.append(str(idx))
    if be[pos:]: parts.append(lua_str(be[pos:]))
    return parts


