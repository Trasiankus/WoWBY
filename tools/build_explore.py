"""Beta helper addon WoWBY_Explore (owner 2026-10-18): every NEW Forever NPC friendly to Alliance and/or Horde, with
its wowhead zones and (once forever_scraper --npc-coords has run) map points -> addon/WoWBY_Explore/data.lua.
The owner walks to them and talks, so WoWBY harvests the gossip still missing before the beta ends.
Sources (no requests): forever-data/en/npcs.json (new NPCs), the saved list pages npcs_list_*.html (react = [A, H]:
1 friendly; location = AreaTable ids), forever-data/en/npc_coords.json (scraper, optional), out/db2/AreaTable.tsv.
    python tools/build_explore.py"""
import glob, json, os, sys
sys.stdout.reconfigure(encoding="utf-8")
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
EN = os.path.join(ROOT, "forever-data", "en")
OUT = os.path.join(ROOT, "addon", "WoWBY_Explore", "data.lua")
SKIP_TYPES = {8, 12}                       # critters, non-combat pets: nothing to say


def lua_str(s):
    return '"%s"' % s.replace("\\", "\\\\").replace('"', '\\"').replace("\n", " ")


def main():
    npcs = json.load(open(os.path.join(EN, "npcs.json"), encoding="utf-8"))
    info = {}
    for p in glob.glob(os.path.join(EN, "npcs_list_*.html")):
        h = open(p, encoding="utf-8", errors="replace").read()
        i = h.find('"data":', h.find("new Listview("))
        if i < 0: continue
        try: data, _ = json.JSONDecoder().raw_decode(h, i + 7)
        except ValueError: continue
        for r in data: info[str(r["id"])] = r
    areas = {}
    for line in open(os.path.join(ROOT, "out", "db2", "AreaTable.tsv"), encoding="utf-8"):
        c = line.rstrip("\n").split("\t")
        if len(c) > 3 and c[1] == "AreaName_lang": areas[c[0]] = c[3]
    cp = os.path.join(EN, "npc_coords.json")
    coords = json.load(open(cp, encoding="utf-8")) if os.path.exists(cp) else {}
    rows, stat = [], {"A": 0, "H": 0, "coords": 0}
    for k, v in sorted(npcs.items(), key=lambda kv: int(kv[0])):
        r = info.get(k) or {}
        react = (v.get("react") or r.get("react") or [None, None]) + [None, None]
        f = (1 if react[0] == 1 else 0) | (2 if react[1] == 1 else 0)
        typ = v.get("type", r.get("type"))
        if not f or typ in SKIP_TYPES: continue
        zones = [areas.get(str(a)) for a in (v.get("location") or r.get("location") or []) if areas.get(str(a))]
        pts = []
        for s in (coords.get(k) or {}).get("spawns") or []:
            for x, y in (s.get("coords") or [])[:20]:
                pts.append("{%d,%.1f,%.1f}" % (s["uiMapId"], x, y))
            if s.get("uiMapName") and s["uiMapName"] not in zones: zones.append(s["uiMapName"])
        stat["A"] += f & 1 > 0; stat["H"] += f & 2 > 0; stat["coords"] += bool(pts)
        rows.append("[%s]={n=%s,t=%s,f=%d,z={%s},p={%s}}," % (
            k, lua_str(v.get("name") or r.get("name") or "?"), lua_str(v.get("tag") or r.get("tag") or ""), f,
            ",".join(lua_str(z) for z in zones), ",".join(pts)))
    os.makedirs(os.path.dirname(OUT), exist_ok=True)
    with open(OUT, "w", encoding="utf-8", newline="\n") as fo:
        fo.write("-- generated by tools/build_explore.py; f = 1 Alliance-friendly, 2 Horde-friendly, 3 both\n")
        fo.write("WoWBY_ExploreData = {\n" + "\n".join(rows) + "\n}\n")
    print("%d NPCs (Alliance-friendly %d, Horde-friendly %d), with map points %d -> %s" % (
        len(rows), stat["A"], stat["H"], stat["coords"], os.path.relpath(OUT, ROOT)))


if __name__ == "__main__":
    main()
