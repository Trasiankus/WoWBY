local function player_word(text, p, en, fem_tab, masc_tab, case_tab, n)
    local female = UnitSex("player") == 3
    local cf = n and case_tab and en and case_tab[en]
    local be = cf and cf[female and 2 or 1][n] or (en and (female and fem_tab[en] or masc_tab[en]))
    if not be then return en or "" end                   -- unknown class / race: the client's own word, no stray digit
    if sentence_start(text, p) then return cf and W.cyr_cap(be) or be end
    return cyr_lower(be)
end
-- NPC gossip / speech / mail by EN text (R55): exact, trimmed, then with the player's name / race / class put back
-- as $N / $R / $C (the server fills them in; build_addon gossip_keys stores those keys, $g lines in both variants)
local function esc_pat(s) return (s:gsub("%p", "%%%0")) end
-- R338: the text is RENDERED here ($G by player sex, $N, $B…): a caller that skipped W.substitute showed a raw
-- «$Gнакіраваў:накіравала;» in an NPC greeting. Rendering twice is harmless (no tokens left after the first).
local gossip_raw, gossip_norm, gossip_norm_index, gossip_other_name
-- the player's own name / race / class in a text → $N / $R / $C (gossip lookup and harvest)
function W.player_tokens(t)
    local k = t
    local me = plain(UnitName("player"))
    if me and me ~= "" then k = k:gsub(esc_pat(me), "$N") end
    -- EN "$c" renders lowercase ("I am sorry, druid, …", R355) → the lowercase class / race is replaced too
    -- (whole words only: "mage" inside "damage")
    local function word(s) return "%f[%a]" .. esc_pat(s:lower()) .. "%f[%A]" end
    local race, class = plain((UnitRace("player"))), plain((UnitClass("player")))
    -- R715: the capitalised form is a whole word too ("Gnomeregan" had become "$Rregan" for a gnome player)
    local function cap(s) return "%f[%a]" .. esc_pat(s) .. "%f[%A]" end
    if race and race ~= "" then k = k:gsub(cap(race), "$R"):gsub(word(race), "$R") end
    if class and class ~= "" then k = k:gsub(cap(class), "$C"):gsub(word(class), "$C") end
    return k
end
function W.gossip_be(t)
    local b = gossip_raw(t)
    return b and W.substitute(b) or nil
end
gossip_raw = function(t)
    t = plain(t)
    if not t or t == "" then return nil end
    local b = W.G[t] or W.G[W.strtrim(t)]
    if b then return b end
    -- the server sends two spaces after a sentence, the world-DB keys have one (R236: Razor Hill grunt answers)
    local one = t:find("  ", 1, true) and W.strtrim((t:gsub("  +", " ")))
    b = one and W.G[one]
    if b then return b end
    local k = W.player_tokens(t)
    if k ~= t then
        -- hand keys (gossip_fix.tsv) may keep Blizzard's lowercase $n / $r / $c
        local lo = k:gsub("%$([NRC])", function(c) return "$" .. c:lower() end)
        b = W.G[k] or W.G[W.strtrim(k)] or W.G[lo] or W.G[W.strtrim(lo)]
        if b then return b end
    end
    -- R514: keys and live texts differ in line breaks (\r\n / \n / $B) and double spaces, sometimes both at once
    -- (trainer greetings, the bear spirit, NPC mail were collected as "untranslated") → one normalised index
    return gossip_norm_index()[gossip_norm(t)] or (k ~= t and gossip_norm_index()[gossip_norm(k)]) or gossip_other_name(t)
end
-- R820: "$n" filled with SOMEONE ELSE's name (an NPC toasting "Dexius", BroadcastText 576): keys holding $N become
-- anchored patterns, bucketed by their first / last 12 characters (when those hold no token); the name found goes
-- into the BE text, and $G there takes the masculine form (that person's sex is unknown)
local NAMED
local function named_index()
    if NAMED then return NAMED end
    NAMED = { head = {}, tail = {} }
    for key, v in pairs(W.G) do
        if type(key) == "string" and type(v) == "string" and key:find("%$[Nn]") then
            local n = gossip_norm(key)
            local p = "^" .. n:gsub("%$N", "\1"):gsub("%p", "%%%0"):gsub("\1", "([^\n]-)") .. "$"
            local h, tl = n:sub(1, 12), n:sub(-12)
            local side, bk = (not h:find("$", 1, true)) and "head" or (not tl:find("$", 1, true)) and "tail", nil
            bk = side == "head" and h or tl
            if side then
                NAMED[side][bk] = NAMED[side][bk] or {}
                table.insert(NAMED[side][bk], { p, v })
            end
        end
    end
    return NAMED
end
gossip_other_name = function(t)
    local n = gossip_norm(t)
    local ix = named_index()
    for _, l in ipairs({ ix.head[n:sub(1, 12)] or {}, ix.tail[n:sub(-12)] or {} }) do
        for _, e in ipairs(l) do
            local caps = { n:match(e[1]) }
            local who = caps[1]
            local same = who and who ~= "" and #who <= 40
            for _, c in ipairs(caps) do if c ~= who then same = false end end
            if same then
                local b = e[2]:gsub("%$[Gg]([^:;]*):([^;]*);", "%1"):gsub("%$[Nn]", (who:gsub("%%", "%%%%")))
                return b
            end
        end
    end
    return nil
end
gossip_norm = function(s)
    s = s:gsub("\r", ""):gsub("%$[Bb]", "\n"):gsub("%$([nrc])", function(c) return "$" .. c:upper() end)
    return W.strtrim((s:gsub("[ \t]+", " "):gsub(" *\n *", "\n")))
end
local GN
gossip_norm_index = function()
    if not GN then
        GN = {}
        for key, v in pairs(W.G) do
            if type(key) == "string" then GN[gossip_norm(key)] = GN[gossip_norm(key)] or v end
        end
        -- ruRU client (R665): the Russian texts of the same lines (their EN keys via WoWBY_RU.gossip)
        for ru in pairs(W.RU and WoWBY_RU and WoWBY_RU.gossip or {}) do
            local v = W.G[ru]
            if v and not GN[gossip_norm(ru)] then GN[gossip_norm(ru)] = v end
        end
    end
    return GN
end
function W.substitute(text, qid, en)
    if not text or not string.find(text, "%$") then return text end
    local lost = false
    text = gsub(text, "%$(%d+)[oO][aA]", function(n)
        local v = objective_amount(tonumber(n), qid, en)
        if not v then lost = true end
        return v or ""
    end)
    if lost then text = gsub(text, "  +", " ") end
    local female = (UnitSex("player") == 3)
    text = gsub(text, "%$[Gg]([^:;]*):([^;]*);", function(m, f) return female and f or m end)
    -- R694: "$Sчуў:чула;" = the SPEAKING NPC's sex (uppercase S only): W.speaker while a caller set it (speech by the
    -- event's GUID, 0 = unknown), else the gossip / quest NPC; unknown → masculine
    if string.find(text, "$S", 1, true) then
        local s = W.speaker
        if s == nil then s = W.unit_sex("npc") end
        text = gsub(text, "%$S([^:;]*):([^;]*);", function(m, f) return s == 3 and f or m end)
    end
    text = gsub(text, "%$[Bb]", "\n")
    text = gsub(text, "%$[Nn]", player_name())
    -- English class / race names (R665: a ruRU client gives Russian ones; core/ru.lua maps them by the class / race file)
    local cls = W.player_class_en and W.player_class_en() or (UnitClass("player"))
    local race = W.player_race_en and W.player_race_en() or (UnitRace("player"))
    local RM, RF = {}, {}
    for k, v in pairs(W.RACES) do RM[k], RF[k] = v[1], v[2] end
    local src = text
    -- "$c3" (case digit) before a bare "$c": the digit belongs to the token, never left behind as «шаман3»
    text = gsub(src, "()%$[Cc]([1-6]?)", function(p, d)
        return player_word(src, p, cls, W.CLASSES_FEM, W.CLASSES, CLASS_CASES, tonumber(d))
    end)
    src = text
    text = gsub(src, "()%$[Rr]([1-6]?)", function(p, d) return player_word(src, p, race, RF, RM, RACE_CASES, tonumber(d)) end)
    text = gsub(text, "%$%$", "$")
    return text
end

-- Guard: a translation is used only while Forever's live EN title equals the EN title it was made from
-- (WoWBY_QTitleEN). Reworked quests (e.g. 490 "<UNUSED>" -> "Bounty: Gnarlpine Furbolg") fall back to EN.
W.QT = WoWBY_QTitleEN or {}
W.orig_title_text = GetTitleText           -- captured before the getter wrap below
local guard = {}                               -- qid -> true/false, decided once per session
local function live_en_title(quest_id)
    local t = C_QuestLog and C_QuestLog.GetTitleForQuestID and C_QuestLog.GetTitleForQuestID(quest_id)
    if (not t or t == "") and GetQuestID and GetQuestID() == quest_id and W.orig_title_text then t = W.orig_title_text() end
    return t ~= "" and t or nil
end
function W.entry_for(quest_id)
    if not quest_id or quest_id == 0 or not W.on("quests") then return nil end
    local k = tostring(quest_id)
    local e = W.Q[k]
    if not e then return nil end
    local want = W.QT[k]
    if not want then return e end
    -- ruRU client (R665): the live title is Russian, so the EN comparison cannot run; the build marks the quests whose
    -- Forever EN title differs from the WoWBY source (WoWBY_QReworkRU) instead
    if W.RU then
        if guard[k] == nil then guard[k] = not (WoWBY_QReworkRU or {})[tonumber(k) or -1] end
        return guard[k] and e or nil
    end
    if guard[k] == nil then
        local live = live_en_title(quest_id)
        if not live then return e end          -- unknown yet: trust, re-check next time
        -- case and spacing don't count: "Your Place in the World" vs "In The" (R481), "One Shot. One Kill." vs two spaces (R807)
        local function key(s) return W.strtrim(s):gsub("%s+", " "):lower() end
        guard[k] = key(live) == key(want)
    end
    return guard[k] and e or nil
end
-- untranslated = no WoWBY text for that field, or the translation was rejected by the title guard
function W.needs_harvest(quest_id, field)
    if not quest_id or quest_id == 0 then return false end
    local k = tostring(quest_id)
    local e = W.Q[k]
    return not (e and e[field]) or guard[k] == false
end
function W.be_title(quest_id)
    local e = W.entry_for(quest_id)
    return e and e.t and W.substitute(e.t) or nil
end

-- Belarusian-capable copies of the client faces (the enUS/ruRU ones lack і/ў). MORPHEUS/SKURRI are built
-- from Forever's own *_cyr fonts by tools/build_fonts.py; FRIZQT_BY = Forever's FRIZQT___CYR (already has і/ў).
local FONTS_BY = { { "MORPHEUS", "Interface\\AddOns\\WoWBY\\Fonts\\MORPHEUS_BY.ttf" },
                   { "SKURRI",   "Interface\\AddOns\\WoWBY\\Fonts\\SKURRI_BY.ttf" },
                   { "FRIZQT",   W.FONT } }
function W.by_font(file)
    local u = (file or ""):upper()
    for _, m in ipairs(FONTS_BY) do if u:find(m[1], 1, true) then return m[2] end end
end
-- Blizzard_Menu's compositor regions raise an error on merely INDEXING SetFont ("Use of function 'SetFont' is
-- disallowed"), so the whole lookup + call is protected; menus skip it anyway (their Font objects are repointed).
local function set_font_raw(fs)
    local file, sz, fl = fs:GetFont()
    if not sz or sz <= 0 then return end                 -- not laid out yet: a size-0 font renders nothing
    local by = W.by_font(file) or W.FONT
    if file == by then return end                        -- already a Belarusian face (Font objects are patched)
    fs:SetFont(by, sz, fl or "")
end
function W.set_font(fs)
    if fs then pcall(set_font_raw, fs) end
end
-- Preload the Belarusian font files (WowUkrainizer does the same): a FontString switched to a font the client
-- has not loaded yet renders blank until something else loads it ("World" vanished, 2026-09-25).
do
    local pre = CreateFrame("Frame", nil, UIParent)
    pre:SetPoint("TOP", UIParent, "BOTTOM", 0, -500)
    pre:SetSize(100, 100)
    for _, m in ipairs(FONTS_BY) do
        local fs = pre:CreateFontString()
        fs:SetAllPoints()
        if pcall(fs.SetFont, fs, m[2], 14, "") then pcall(fs.SetText, fs, "Ўў Іі Ёё cache") end
    end
end

-- replace the EN title inside a decorated string ("[30] Title", icons, colour codes) -> keeps decorations
local QUEST_TAGS_BE = { Elite = "Элітнае", Dungeon = "Падзямелле", Raid = "Рэйд", Group = "Групавое", PvP = "PvP",
                  Daily = "Штодзённае", Weekly = "Штотыднёвае", Legendary = "Легендарнае", Failed = "Праваленае",
                  Complete = "Выканана" }
function W.swap_title(fs, quest_id)
    if not (fs and fs.GetText and W.is_be()) then return end
    local be = W.be_title(quest_id)
    local en = C_QuestLog and C_QuestLog.GetTitleForQuestID and C_QuestLog.GetTitleForQuestID(quest_id)
    local cur = plain(fs:GetText())
    if not (be and en and cur) or en == "" then return end
    local s, e = string.find(cur, en, 1, true)
    if s then
        W.set_font(fs)
        -- the tag after the title: "WANTED: Vulgara (Elite)" → «… (Элітнае)» (owner 2026-10-13, R523: agrees with «заданне»)
        -- (a ruRU client's tag is Russian: «(Элитное)» → its EN word first, R665)
        local tail = cur:sub(e + 1):gsub("%(([^()|]+)%)", function(w)
            local b = QUEST_TAGS_BE[w] or (W.ru_get and W.ru_get(QUEST_TAGS_BE, "ui", w))
            return b and ("(" .. b .. ")") or nil
        end)
        fs:SetText(cur:sub(1, s - 1) .. be .. tail)
    end
end

-- Cyrillic-aware lowercase (string.lower in WoW only handles ASCII)
local LOWER = {}
do
    local up, lo = "АБВГДЕЁЖЗІЙКЛМНОПРСТУЎФХЦЧШЫЬЭЮЯ", "абвгдеёжзійклмнопрстуўфхцчшыьэюя"
    local u, l = {}, {}
    for ch in up:gmatch("[\192-\255][\128-\191]*") do u[#u + 1] = ch end
    for ch in lo:gmatch("[\192-\255][\128-\191]*") do l[#l + 1] = ch end
    for i = 1, #u do LOWER[u[i]] = l[i] end
end
function cyr_lower(t)
    t = t:gsub("[A-Z]", function(c) return string.char(c:byte() + 32) end)       -- ASCII only, locale-proof
    return (t:gsub("[\208\209][\128-\191]", function(c) return LOWER[c] end))
end
local UPPER = {}
for u, l in pairs(LOWER) do UPPER[l] = u end
function W.cyr_cap(t)                                     -- first letter upper-case («шаману» → «Шаману»)
    return (t:gsub("^[\208\209][\128-\191]", function(c) return UPPER[c] or c end))
end
