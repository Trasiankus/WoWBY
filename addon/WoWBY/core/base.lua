-- $C / $R in Belarusian text: the player's class/race in Belarusian, gendered by the player's sex; lowercase
-- inside a sentence («адважны друід»), capital at a sentence start («Друідка, …»). The client is enUS, so
-- UnitClass/UnitRace give English names; no match -> the English word stays.
local function sentence_start(text, p)
    local before, n = text:sub(1, p - 1), 1
    while n > 0 do                                        -- drop spaces and opening quotes/brackets before the token
        local m
        before, n = before:gsub("%s+$", "")
        before, m = before:gsub("«$", ""); n = n + m
        before, m = before:gsub("[\"%(]$", ""); n = n + m
    end
    return before == "" or before:find("[%.!%?\n]$") ~= nil
end
