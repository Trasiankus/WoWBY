-- Secret values (this client): some texts (nameplate previews, restricted units) are "secret" — addon code may not
-- even compare them ("attempt to compare … a secret string value", 2026-09-26). Every text we did not write goes
-- through plain(): a normal string, or nil.
function plain(v)
    if type(v) ~= "string" or (issecretvalue and issecretvalue(v)) then return nil end
    return v
end
-- Tooltip data with ANY secret value (combat: action-button cooldown lines, auras…) is left completely alone.
-- Writing even one plain line into such data taints Blizzard's later processing of the secret lines
-- ("attempt to index local 'color' (a secret table value, while execution tainted by 'WoWBY')", 2026-09-28).
W.TIP = { secret = setmetatable({}, { __mode = "k" }), keep = setmetatable({}, { __mode = "k" }) }   -- one local (main chunk is at Lua's 200-local limit)
do
    local secret = W.TIP.secret                                -- tooltip -> true while its current data is unsafe
    local function is_secret(v) return v ~= nil and issecretvalue and issecretvalue(v) or false end
    local function data_unsafe(data)
        if type(data) ~= "table" then return false end
        if is_secret(data.id) or is_secret(data.guid) or is_secret(data.lines) then return true end
        for _, l in ipairs(data.lines or {}) do
            if is_secret(l) or is_secret(l.leftText) or is_secret(l.rightText) or is_secret(l.leftColor)
                or is_secret(l.rightColor) or is_secret(l.type) then
                return true
            end
        end
        return false
    end
    local TDP = TooltipDataProcessor
    -- bilingual mode (R369/R381, option WoWBY_DB.dual; owner: "EN full standard card, then BY full below after a
    -- separator"): for item / spell / aura / quest-link tooltips in GameTooltip / ItemRefTooltip our pre-calls translate a
    -- COPY of the tooltip data — the real data stays English and is drawn as Blizzard's normal card; one post-call then
    -- runs the line rules on the copy and appends a separator + the copy's lines (same colours, left / right columns).
    -- W.TIP.dual[tt] = that copy while it is shown: every other WoWBY pass leaves such a tooltip alone.
    -- copy path only where the data id matters (item names / suffixes by id, quest objectives by quest id); spells,
    -- talents, auras get lines AddLine'd after their data ("Passive" + description of a talent, R395) → a data copy
    -- misses them, so they go the "plain" way (the finished English lines are read on show)
    local DUAL_TYPES = { [0] = true, [23] = true }                            -- Item, Quest
    local DUAL_FRAMES = { GameTooltip = true, ItemRefTooltip = true }
    -- R393: any OTHER data (talents: their own type, or none; mixed talent + next-rank spell) → "plain" mode for this
    -- tooltip build: nothing is translated in place while it is built; tooltips.lua dual_plain reads the finished English
    -- lines on show and appends the Belarusian. Units / corpses / objects / minimap blips are never bilingual.
    local NOT_DUAL = { [2] = true, [3] = true, [4] = true, [21] = true }
    local dual_src = setmetatable({}, { __mode = "k" })                         -- tooltip -> the data its copy is of
    W.TIP.plain = setmetatable({}, { __mode = "k" })
    W.TIP.dual = setmetatable({}, { __mode = "k" })
    local line_fns = {}                                                         -- TIP.line callbacks, re-run on the copy
    function W.dual_on() return WoWBY_DB and WoWBY_DB.dual and W.is_be() end
    function W.dual_hide(tt)                                    -- the separator texture, when a tooltip is not bilingual
        local d = W.TIP.divider and tt and W.TIP.divider[tt]
        if d then d:Hide() end
    end
    -- outside data processing (OnShow / OnUpdate passes): is this still the bilingual card? GameTooltip is reused for
    -- plain SetText tooltips without being hidden — then line 1 differs from the title the card was built with
    local dual_title = setmetatable({}, { __mode = "k" })
    function W.dual_active(tt)
        if not (tt and W.TIP.dual[tt]) then return false end
        local name = tt.GetName and tt:GetName()
        local fs = name and _G[name .. "TextLeft1"]
        local t = fs and fs:GetText()
        if (issecretvalue and t ~= nil and issecretvalue(t)) or t ~= dual_title[tt] then
            W.TIP.dual[tt] = nil; W.dual_hide(tt)
            return false
        end
        return true
    end
    W.TIP.dual_title = dual_title
    -- separator (R382): an empty line + our own 1-px texture across the whole tooltip at that line (a row of dashes
    -- left gaps); one texture per tooltip, hidden again by W.dual_hide. Also records the card's title (W.dual_active).
    function W.dual_divider(tt)
        tt:AddLine(" ")
        local name = tt:GetName()
        local fs = name and _G[name .. "TextLeft" .. tt:NumLines()]
        local div = W.TIP.divider and W.TIP.divider[tt]
        if not div and tt.CreateTexture then
            W.TIP.divider = W.TIP.divider or setmetatable({}, { __mode = "k" })
            div = tt:CreateTexture(nil, "ARTWORK")
            div:SetColorTexture(0.62, 0.55, 0.35, 0.55)             -- muted gold, like Blizzard's dividers
            div:SetHeight(1)
            W.TIP.divider[tt] = div
        end
        if div and fs then
            div:ClearAllPoints()
            div:SetPoint("LEFT", tt, "LEFT", 10, 0)
            div:SetPoint("RIGHT", tt, "RIGHT", -10, 0)
            div:SetPoint("TOP", fs, "CENTER", 0, 0)
            div:Show()
        end
        local t1 = name and _G[name .. "TextLeft1"]
        dual_title[tt] = t1 and t1:GetText()
    end
    local function copy_data(data)
        local c = {}
        for k, v in pairs(data) do c[k] = v end
        c.lines = {}
        for i, l in ipairs(data.lines) do
            local n = {}
            for k, v in pairs(l) do n[k] = v end
            n.wowby_en = { l.leftText, l.rightText }                -- to skip lines that stayed English (F6 hint)
            c.lines[i] = n
        end
        return c
    end
    local function dual_for(tt, data, kind)
        -- R385: spell-book tooltips (SetSpellBookItem) come without data.type → the callback's own kind counts too
        if not (W.dual_on() and tt and type(data) == "table" and data.lines
                and (DUAL_TYPES[data.type] or DUAL_TYPES[kind])) then return nil end
        local name = tt.GetName and tt:GetName()
        if not (name and DUAL_FRAMES[name]) or W.TIP.plain[tt] then return nil end
        if dual_src[tt] ~= data then W.TIP.dual[tt] = copy_data(data); dual_src[tt] = data end
        return W.TIP.dual[tt]
    end
    function W.TIP.pre(kind, fn)
        if not (TDP and TDP.AddTooltipPreCall and kind) then return end
        TDP.AddTooltipPreCall(kind, function(tt, data)
            local bad = data_unsafe(data)
            if tt then secret[tt] = bad or nil end
            if bad then return end
            -- R393: decide "plain" bilingual mode per tooltip build (a build starts with an empty tooltip)
            if tt and W.dual_on() and type(data) == "table" then
                local name = tt.GetName and tt:GetName()
                if name and DUAL_FRAMES[name] then
                    if tt:NumLines() == 0 then                    -- a new build: forget the previous card
                        W.TIP.plain[tt] = nil; W.TIP.dual[tt] = nil; dual_src[tt] = nil; dual_title[tt] = nil
                        W.dual_hide(tt)
                    end
                    local ty = data.type
                    if ty == nil and type(kind) == "number" then ty = kind end
                    if not DUAL_TYPES[ty] and not NOT_DUAL[ty] then W.TIP.plain[tt] = true end
                    if W.TIP.plain[tt] then W.TIP.dual[tt] = nil; return end     -- English while built
                end
            end
            local c = dual_for(tt, data, kind)
            if c then return fn(tt, c) end                   -- translate the copy; the drawn card stays English
            if tt and dual_src[tt] ~= data then W.TIP.dual[tt] = nil; dual_src[tt] = nil; W.dual_hide(tt) end
            return fn(tt, data)
        end)
    end
    function W.TIP.line(kind, fn)
        if not (TDP and TDP.AddLinePreCall and kind) then return end
        line_fns[#line_fns + 1] = fn
        TDP.AddLinePreCall(kind, function(tt, ld)
            if (tt and secret[tt]) or data_unsafe({ lines = { ld } }) then return end
            if tt and (W.TIP.dual[tt] or W.TIP.plain[tt]) then return end   -- bilingual: English card as is
            return fn(tt, ld)
        end)
    end
    function W.TIP.post(kind, fn)
        if not (TDP and TDP.AddTooltipPostCall and kind) then return end
        TDP.AddTooltipPostCall(kind, function(tt, data)
            if (tt and secret[tt]) or data_unsafe(data) then return end
            if tt and (W.TIP.dual[tt] or W.TIP.plain[tt]) then return end
            return fn(tt, data)
        end)
    end
    local function rgb(c) if type(c) == "table" and c.GetRGB then return c:GetRGB() end return 1, 1, 1 end
    local SELL_PRICE = Enum and Enum.TooltipDataLineType and Enum.TooltipDataLineType.SellPrice
    if TDP and TDP.AddTooltipPostCall and TDP.AllTypes then
        TDP.AddTooltipPostCall(TDP.AllTypes, function(tt, data)
            local c = tt and W.TIP.dual[tt]
            if not (c and dual_src[tt] == data) or secret[tt] or W.TIP.plain[tt] then return end
            for _, l in ipairs(c.lines) do
                for _, fn in ipairs(line_fns) do pcall(fn, tt, l) end
            end
            W.dual_divider(tt)
            for _, l in ipairs(c.lines) do
                local lt, rt = l.leftText, l.rightText
                local en = l.wowby_en or {}
                -- (a line that stayed in the client's language: Latin words, or Russian on a ruRU client — R665)
                local same = lt == en[1] and rt == en[2] and type(lt) == "string"
                    and (lt:find("[A-Za-z][A-Za-z]") or (W.RU and lt:find("[\208\209]")))
                if type(lt) == "string" and lt ~= "" and l.type ~= SELL_PRICE and not same then
                    if type(rt) == "string" and rt ~= "" then
                        local lr, lg, lb = rgb(l.leftColor)
                        local rr, rg, rb = rgb(l.rightColor)
                        tt:AddDoubleLine(lt, rt, lr, lg, lb, rr, rg, rb)
                    else
                        local r, g, b = rgb(l.leftColor)
                        tt:AddLine(lt, r, g, b, true)
                    end
                end
            end
        end)
    end
end
-- language switch (R384): every text WoWBY writes into a Blizzard FontString / button goes through W.swap, which
-- remembers the English it replaced; switching to English puts it back wherever our Belarusian is still shown
-- (Blizzard rewrites most of them itself later; this covers what stays: headers, quest details, map breadcrumbs…)
local swapped = setmetatable({}, { __mode = "k" })          -- region -> { en, be }
-- every FontString under a frame (its regions, then its children's, down to max_depth): fn(fs). Forbidden frames
-- (some Blizzard_Menu parts) and branches where skip(frame) is true are left out.
function W.each_fs(frame, max_depth, fn, skip, depth)
    depth = depth or 0
    if not frame or depth > max_depth or (frame.IsForbidden and frame:IsForbidden()) or (skip and skip(frame)) then return end
    if frame.GetRegions then
        for _, r in ipairs({ frame:GetRegions() }) do
            if r.GetObjectType and r:GetObjectType() == "FontString" then fn(r) end
        end
    end
    if frame.GetChildren then
        for _, c in ipairs({ frame:GetChildren() }) do W.each_fs(c, max_depth, fn, skip, depth + 1) end
    end
end
function W.swap(obj, be, ...)
    if not obj then return end
    local cur = obj.GetText and obj:GetText()
    if cur ~= nil and issecretvalue and issecretvalue(cur) then cur = nil end
    local r = swapped[obj]
    if type(be) == "string" and type(cur) == "string" and cur ~= be then
        if r and r.be == cur then r.be = be                    -- re-swap of our own text: keep the first English
        else swapped[obj] = { en = cur, be = be } end
    end
    obj:SetText(be, ...)
end
function W.restore_en()
    for obj, r in pairs(swapped) do
        local cur = obj.GetText and obj:GetText()
        if cur ~= nil and not (issecretvalue and issecretvalue(cur)) and cur == r.be then pcall(obj.SetText, obj, r.en) end
    end
    wipe(swapped)
end
function W.sid_ok(v)            -- a usable table key: tooltip ids can be SECRET numbers (auras in combat)
    if v == nil or (issecretvalue and issecretvalue(v)) then return nil end
    return v
end
function W.unit_sex(u)            -- UnitSex (2 male, 3 female) or nil: no such unit / secret
    if not UnitExists(u) then return nil end
    return W.sid_ok(UnitSex(u))
end
-- R694: the sex of the NPC behind a GUID (speech events): any unit token showing it, else nil (= masculine)
function W.guid_sex(g)
    g = W.sid_ok(g)
    if type(g) ~= "string" then return nil end
    for _, u in ipairs({ "npc", "target", "mouseover", "focus", "targettarget" }) do
        if W.sid_ok(UnitGUID(u)) == g then return W.unit_sex(u) end
    end
    for i = 1, 40 do
        local u = "nameplate" .. i
        if W.sid_ok(UnitGUID(u)) == g then return W.unit_sex(u) end
    end
    return nil
end
-- R694: run f(...) with the speaker's sex fixed for W.substitute ($S…); 0 / nil sex = unknown (masculine)
function W.as_speaker(sex, f, ...)
    local old = W.speaker
    W.speaker = sex or 0
    local ok, a, b = pcall(f, ...)                             -- (two results are enough for every caller)
    W.speaker = old
    if not ok then error(a, 0) end
    return a, b
end
