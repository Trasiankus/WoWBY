function W.prune_harvest()
    local h = WoWBY_DB and WoWBY_DB.harvest and WoWBY_DB.harvest[GetLocale()]
    if not h then return end
    -- quests field by field (R677): a translated quest kept its harvested progress / completion text only until the
    -- next login, so a field the corpus still lacks was lost when no import ran in between
    for k, fields in pairs(h.quests or {}) do
        if type(fields) == "table" and W.needs_harvest then
            for f in pairs(fields) do
                local ok, need = pcall(W.needs_harvest, tonumber(k), f)
                if ok and not need then fields[f] = nil end
            end
            if not next(fields) then h.quests[k] = nil end
        end
    end
    local done = {
        names = function(k) return W.N[k] end,
        objects = function(k) return W.N[k] or W.IE[k] end,             -- R968: lootable objects named like items
        zones = function(k) return W.Z[k] end,
        gossip = function(k) return W.gossip_be and W.gossip_be(k) end,
        objectives = function(k)
            local rest = k:gsub("^%d+/%d+", ""):gsub("[Ss]lain", "")
            return (not rest:find("%a")) or (W.obj_line_be and W.obj_line_be(k))   -- R968: "0/8   slain" = name not loaded
        end,
        books = function(k) return (WoWBY_Books or {})[k] end,
    }
    for kind, ok in pairs(done) do
        for k in pairs(h[kind] or {}) do
            local hit = false
            pcall(function() hit = ok(k) and true or false end)
            if hit then h[kind][k] = nil end
        end
    end
    for k, v in pairs(h.items or {}) do                -- R734: by id or by the harvested EN name
        if W.IT[tonumber(k)] or (type(v) == "table" and W.IE[v.n]) then h.items[k] = nil end
    end
    -- R836 (owner 2026-11-08): entries the last import already took in (build: WoWBY_HarvestSeen from data/harvest.json)
    -- are dropped too, so the counter restarts after every import + build
    local seen = WoWBY_HarvestSeen and WoWBY_HarvestSeen[GetLocale()]
    if seen then
        for kind, keys in pairs(seen) do
            local t = h[kind]
            if type(t) == "table" then
                for k, v in pairs(keys) do
                    if kind == "quests" and type(v) == "table" and type(t[k]) == "table" then
                        for f in pairs(v) do t[k][f] = nil end
                        if not next(t[k]) then t[k] = nil end
                    elseif kind ~= "quests" then
                        t[k] = nil
                    end
                end
            end
        end
    end
end

