-- the hero's Belarusian name is PER CHARACTER (R128, 2026-09-30): WoWBY_DB.name_be_char["Name-Realm"]. The old
-- account-wide WoWBY_DB.name_be moves to the first character whose EN name starts with the same letter.
local FIRST = { A = "А", B = "Б", C = "К", D = "Д", E = "Э", F = "Ф", G = "Г", H = "Х", I = "І", J = "Д", K = "К", L = "Л",
                M = "М", N = "Н", O = "А", P = "П", Q = "К", R = "Р", S = "С", T = "Т", U = "У", V = "В", W = "У", X = "К",
                Y = "Й", Z = "З" }
function W.char_key()
    return (UnitName("player") or "?") .. "-" .. (GetRealmName and GetRealmName() or "")
end
function W.my_name_be()
    if not WoWBY_DB then return nil end
    WoWBY_DB.name_be_char = WoWBY_DB.name_be_char or {}
    local k = W.char_key()
    local old = WoWBY_DB.name_be
    if old and old ~= "" and WoWBY_DB.name_be_char[k] == nil then
        local en = UnitName("player") or ""
        local cy = old:sub(1, 2)                         -- first Cyrillic letter = 2 bytes
        if FIRST[en:sub(1, 1):upper()] == cy then
            WoWBY_DB.name_be_char[k] = old
            WoWBY_DB.name_be = nil
        end
    end
    return WoWBY_DB.name_be_char[k]
end
function W.set_my_name_be(v)
    if not WoWBY_DB then return end
    WoWBY_DB.name_be_char = WoWBY_DB.name_be_char or {}
    WoWBY_DB.name_be_char[W.char_key()] = v
end
local function player_name()
    local nb = W.my_name_be()
    if nb and nb ~= "" and W.is_be() then return nb end
    return UnitName("player") or ""
end

-- run W[name]() and keep going on error; the last errors are kept in WoWBY_DB.errors (read from SavedVariables:
-- WoW hides Lua errors unless scriptErrors is on)
-- R970: one line into WoWBY_DB.errors (newest first, 20 kept) — for runtime hooks that are not W.safe steps
function W.log_error(msg)
    if not WoWBY_DB then return end
    WoWBY_DB.errors = WoWBY_DB.errors or {}
    local e = WoWBY_DB.errors
    table.insert(e, 1, date("%Y-%m-%d %H:%M ") .. tostring(msg))
    for i = #e, 21, -1 do e[i] = nil end
end
function W.safe(name, ...)
    local fn = W[name]
    if type(fn) ~= "function" then return end
    local ok, err = pcall(fn, ...)
    if not ok and WoWBY_DB then
        WoWBY_DB.errors = WoWBY_DB.errors or {}
        local e = WoWBY_DB.errors
        table.insert(e, 1, date("%Y-%m-%d %H:%M ") .. name .. ": " .. tostring(err))
        for i = #e, 21, -1 do e[i] = nil end
        if geterrorhandler then geterrorhandler()(err) end
    end
end
-- R856 (owner 2026-11-09: a finished objective left the tracker block un-redrawn): the game hides Lua errors, so errors
-- that name WoWBY, taint or the objective tracker are also kept in WoWBY_DB.blizz_errors (last 30, with a short stack;
-- each distinct message once per session). The previous handler still runs.
if seterrorhandler and geterrorhandler then
    local prev, seen = geterrorhandler(), {}
    seterrorhandler(function(msg, ...)
        pcall(function()
            local m = tostring(msg)
            if seen[m] or not WoWBY_DB then return end
            if not (m:find("WoWBY") or m:find("taint") or m:find("ObjectiveTracker") or m:find("secret")) then return end
            seen[m] = true
            WoWBY_DB.blizz_errors = WoWBY_DB.blizz_errors or {}
            local e = WoWBY_DB.blizz_errors
            table.insert(e, 1, date("%Y-%m-%d %H:%M ") .. m .. "\n" .. ((debugstack and debugstack(3, 8, 6)) or ""))
            for i = #e, 31, -1 do e[i] = nil end
        end)
        if prev then return prev(msg, ...) end
    end)
end
-- R951 (owner: "Interface action failed because of an AddOn" — logged?): those come as events, not Lua errors →
-- ADDON_ACTION_BLOCKED / FORBIDDEN are kept in WoWBY_DB.blizz_errors too (which addon, which protected function, time,
-- whether in combat). Every addon's, so we see whether WoWBY or another addon caused it.
do
    local f = CreateFrame("Frame")
    f:RegisterEvent("ADDON_ACTION_BLOCKED"); f:RegisterEvent("ADDON_ACTION_FORBIDDEN")
    f:SetScript("OnEvent", function(_, event, addon, func)
        pcall(function()
            if not WoWBY_DB then return end
            WoWBY_DB.blizz_errors = WoWBY_DB.blizz_errors or {}
            local e = WoWBY_DB.blizz_errors
            table.insert(e, 1, date("%Y-%m-%d %H:%M ") .. event .. " addon=" .. tostring(addon) .. " func=" .. tostring(func)
                .. (InCombatLockdown() and " (in combat)" or ""))
            for i = #e, 31, -1 do e[i] = nil end
        end)
    end)
end
-- ---------- harvest: collect what the game shows that WoWBY can't translate yet ----------
-- Stored per client locale in WoWBY_DB.harvest[locale] (enUS gives source text, ruRU gives references);
-- read out by tools/import_harvest.py (own install) or tools/import_paste.py (players' «Адправіць сабранае» exports).
-- ON by default since R968 (2026-11-13; it was off R677–R967), switch in the options window: see W.harvest_default.
function W.hv_on() return WoWBY_DB and WoWBY_DB.harvest_on and true or false end
function W.harvest_default()
    if not WoWBY_DB then return end
    -- R968 (owner 2026-11-13: "make this one by default"): collecting is ON for everyone now — the export button sends
    -- it to the translator. Switched on once per install (also where R677 had set it off); a later «off» is kept.
    if not WoWBY_DB.hv_default2 then
        WoWBY_DB.hv_default2 = true
        WoWBY_DB.harvest_on = true
        WoWBY_DB.noharvest = nil
        return
    end
    if WoWBY_DB.harvest_on ~= nil then return end
    local had = false
    for _, l in pairs(WoWBY_DB.harvest or {}) do
        if type(l) == "table" then for _, t in pairs(l) do if type(t) == "table" and next(t) then had = true end end end
    end
    -- on by default in TEST clients (beta, the stress-test install: IsTestBuild) — that is where the owner plays to
    -- collect missing text (R684, 2026-10-21: the fresh stress-test install started with it off); off on release
    local test = IsTestBuild and IsTestBuild() and true or false
    WoWBY_DB.harvest_on = ((had or test) and not WoWBY_DB.noharvest) or false
    WoWBY_DB.noharvest = nil
end
local function hv()
    WoWBY_DB.harvest = WoWBY_DB.harvest or {}
    local loc = GetLocale and GetLocale() or "enUS"
    local h = WoWBY_DB.harvest[loc]
    if not h then
        h = { quests = {}, names = {}, zones = {}, gossip = {}, objectives = {} }
        WoWBY_DB.harvest[loc] = h
    end
    h.books = h.books or {}                            -- R138: book pages (added later than the rest)
    -- R600: world-object names from Object tooltips ("Leyline") — never players, so extract keeps them without the
    -- WDB-cache check (a new client build empties the cache, and every harvested name was then dropped)
    h.objects = h.objects or {}
    h.items = h.items or {}                            -- R734: encrypted items {id = {n = EN name, d = {lines}}}
    -- once: names collected before 2026-09-29 were mostly other players / pets (already imported to
    -- data/harvest.json, where extract_forever keeps only NPC / object names seen in the WDB cache)
    if not WoWBY_DB.hv_names2 then
        for _, l in pairs(WoWBY_DB.harvest) do if type(l) == "table" then l.names = {} end end
        WoWBY_DB.hv_names2 = true
    end
    return h
end
function W.harvest_quest(qid, field, text)
    if not (W.hv_on() and qid and qid ~= 0 and type(text) == "string" and text ~= "") then return end
    local q, k = hv().quests, tostring(qid)
    q[k] = q[k] or {}
    -- the player's name / race / class back to $N / $R / $C, like gossip (R485: "Thank you …, Sparkled." reached the queue)
    q[k][field] = W.player_tokens and W.player_tokens(text) or text
end
